/* Create a local .env with fresh secrets (refuses to overwrite one).
 *   npm run setup
 * Generates PII_ENC_KEY and ADMIN_PASSWORD_HASH (prompts for the password,
 * or reads ADMIN_PASSWORD). Keep .env out of git — it's in .gitignore.
 *
 * Back up PII_ENC_KEY somewhere safe (password manager): if it's lost,
 * encrypted customer data in the database cannot be recovered.
 */
"use strict";

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const { hashPassword } = require("../server/password");
const { readNewPassword } = require("./prompt");

const ENV_PATH = path.join(__dirname, "..", ".env");

(async () => {
  if (fs.existsSync(ENV_PATH)) {
    throw new Error(".env already exists — edit it by hand, or use `npm run hash-password` to change the admin password.");
  }
  const pw = await readNewPassword();
  if (pw.length < 12) throw new Error("Use at least 12 characters.");
  const lines = [
    "# Generated by `npm run setup`. Never commit this file.",
    "POSTGRES_URL=" + (process.env.POSTGRES_URL || "postgres://postgres:penstest@localhost:5432/postgres"),
    "ADMIN_PASSWORD_HASH=" + hashPassword(pw),
    "PII_ENC_KEY=" + crypto.randomBytes(32).toString("base64"),
    "# Local http dev: allow the admin cookie without HTTPS.",
    "COOKIE_SECURE=false",
    ""
  ];
  fs.writeFileSync(ENV_PATH, lines.join("\n"), { mode: 0o600 });
  console.log("Wrote .env (mode 600). Back up PII_ENC_KEY in your password manager.");
})().catch((e) => { console.error(e.message); process.exit(1); });
